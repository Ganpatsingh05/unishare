// Regenerates src/features/rides/constants/rideAccentGlyphs.js: the outlined
// "Ride together." headline accent, drawn from Geist so the hands can be part
// of the letters themselves.
//
// One-off tooling, not an app dependency:
//   npm i --no-save fontkit wawoff2
//   node scripts/generate-ride-accent-glyphs.mjs <path-to-Geist-latin.woff2>
//
// The latin Geist variable font is the largest Geist .woff2 that next/font
// writes to .next/static/media after a build.
import fs from "node:fs";
import * as fontkit from "fontkit";
import wawoff2 from "wawoff2";

const [fontPath] = process.argv.slice(2);
if (!fontPath) throw new Error("Usage: node generate-ride-accent-glyphs.mjs <Geist-latin.woff2>");

const TEXT = "Ride together.";
const WEIGHT = 760;
const TRACKING = -35; // -0.035em, as set on the headline
const round = (value) => Math.round(value * 10) / 10;

const ttf = Buffer.from(await wawoff2.decompress(fs.readFileSync(fontPath)));
const font = fontkit.create(ttf).getVariation({ wght: WEIGHT });
const run = font.layout(TEXT);

let pen = 0;
const glyphs = [];
run.glyphs.forEach((glyph, i) => {
  const position = run.positions[i];
  if (TEXT[i].trim()) {
    const path = glyph.path.transform(1, 0, 0, -1, pen + (position.xOffset || 0), -(position.yOffset || 0));
    glyphs.push({ ch: TEXT[i], x: Math.round(pen * 100) / 100, d: path.toSVG().replace(/-?\d+\.\d+/g, (m) => String(round(parseFloat(m)))) });
  }
  pen += position.xAdvance + TRACKING;
});

const out = `// GENERATED by scripts/generate-ride-accent-glyphs.mjs - do not edit by hand.
// Outlines of "${TEXT}" in Geist (SIL Open Font License 1.1), variable
// weight ${WEIGHT}, tracking -0.035em, laid out with kerning. Units: 1000 = 1em,
// origin on the baseline, y down. Each glyph carries its pen position.
export const ACCENT_TEXT = ${JSON.stringify(TEXT)};
export const ACCENT_ADVANCE = ${Math.round(pen * 100) / 100};
export const ACCENT_GLYPHS = ${JSON.stringify(glyphs, null, 2)};
`;
fs.writeFileSync(new URL("../src/features/rides/constants/rideAccentGlyphs.js", import.meta.url), out);
console.log(`wrote ${glyphs.length} glyphs, advance ${Math.round(pen)}`);
